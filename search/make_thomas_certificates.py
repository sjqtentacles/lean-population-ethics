"""Turn each conflict among Arrhenius's conditions into a Lean theorem.

Usage: python3 search/make_thomas_certificates.py
"""

from pathlib import Path

from popsat import Encoding, FineEncoding, conflict_map, ground_core
from thomas import CONDITIONS, LEAN_WITNESS, Scale, ThomasDomain, Witnesses, lst, num, strongest

OUT = Path(__file__).resolve().parent.parent / "PopEthics" / "ArrheniusCertificates.lean"
DEC = "(by decide)"


def hypotheses(s: Scale, w: Witnesses):
    zt = f"{num(s.Z)} {num(s.T)}"
    zat = f"{num(s.Z)} {num(s.A)} {num(s.T)}"
    lw = LEAN_WITNESS
    return {
        "Trans": ("hT", "Trans R"),
        "Refl": ("hRefl", "Refl R"),
        "ED": ("hED", f"ED R {zt}"),
        "Quantity": ("hQ", f"Quantity R {zt} {lw['q']}"),
        "DA": ("hDA", f"DA R {zt}"),
        "IA": ("hIA", f"IA R {zt} {lw['c']}"),
        "NS": ("hNS", f"NS R {zt}"),
        "WNS": ("hWNS", f"WNS R {zt} {w.wns_d}"),
        "NEP": ("hNEP", f"NEP R {zat} {w.nep_b}"),
        "GNE": ("hGNE", f"GNE R {zt} {lw['g2']}"),
        "NE": ("hNE", f"NE R {zt} {lw['g2']}"),
        "GIAA": ("hGIAA", f"GIAA R {zt} {lw['c']}"),
        "IAA": ("hIAA", f"IAA R {zt} {lw['c']}"),
        "GNEP": ("hGNEP", f"GNEP R {zat} {lw['g1']}"),
        "ST": ("hST", f"ST R {zat} {lw['st_b']}"),
        "AvoidRC": ("hARC", f"AvoidRC R {num(s.A)} {w.rc_m}"),
        "AvoidRA": ("hARA", f"AvoidRA R {zat} {w.ra_n}"),
        "AvoidVRC": ("hAVRC", f"AvoidVRC R {num(s.A)} {num(w.vr_z)} {w.vr_m} {w.vr_n}"),
        "AvoidVRA": ("hAVRA", f"AvoidVRA R {zat} {num(w.vr_z)} {w.vr_m} {w.vr_n}"),
    }


def have(k: int, inst, hyp) -> str:
    h = hyp[inst.cond][0]
    kind = inst.args[0]
    if kind == "trans":
        _, a, b, c = inst.args
        return f"  have i{k} := {h}.inst {lst(a)} {lst(b)} {lst(c)}"
    if kind == "refl":
        return f"  have i{k} := {h} {lst(inst.args[1])}"
    _, call, ndec, x, y = inst.args
    px, py = f"(pop {lst(x)})", f"(pop {lst(y)})"
    proof = f"({h} {call} {' '.join([DEC] * ndec)}) {DEC} {DEC}"
    if kind == "rel":
        return f"  have i{k} : R {px} {py} :=\n    rel_perm {proof}"
    if kind == "better":
        return f"  have i{k} : R {px} {py} ∧ ¬ R {py} {px} :=\n    better_perm {proof}"
    return f"  have i{k} : ¬ (R {px} {py} ∧ ¬ R {py} {px}) :=\n    not_better_perm {proof}"


def theorem(conds, core, hyp) -> str:
    conds = [c for c in CONDITIONS if c in conds]
    hyps = "\n    ".join(f"({hyp[c][0]} : {hyp[c][1]})" for c in conds)
    name = "conflict_" + "_".join(c[0].lower() + c[1:] if c in ("Trans", "Refl") else c for c in conds)
    counts = ", ".join(f"{sum(i.cond == c for i in core)} of {c}" for c in conds)
    lines = [
        f"/-- No axiology satisfies {', '.join(conds)} (with the witnesses shown).",
        f"Certificate: {len(core)} ground instances ({counts}). -/",
        f"theorem {name} {{R : Axiology}}\n    {hyps} : False := by",
    ]
    order = {c: i for i, c in enumerate(conds)}
    for k, inst in enumerate(sorted(core, key=lambda i: (order[i.cond], str(i.args))), 1):
        lines.append(have(k, inst, hyp))
    lines.append("  clear " + " ".join(hyp[c][0] for c in conds))
    lines.append("  grind")
    return "\n".join(lines)


def main():
    s = Scale(levels=(-1, 1, 2, 3, 4, 5), max_size=4, T=5)
    w = Witnesses()
    dom = ThomasDomain(s, w)
    hyp = hypotheses(s, w)
    mus, _ = conflict_map(Encoding(dom, CONDITIONS))
    best = strongest(mus)
    fine = FineEncoding(dom, CONDITIONS)
    blocks = []
    for m in sorted(best, key=lambda x: (len(x), [CONDITIONS.index(c) for c in CONDITIONS if c in x])):
        core = ground_core(dom, [c for c in CONDITIONS if c in m], fine)
        print(f"{[c for c in CONDITIONS if c in m]}: {len(core)} ground instances")
        blocks.append(theorem(m, core, hyp))
    header = f'''import PopEthics.Arrhenius

/-!
# Conflicts among Arrhenius's conditions, found by SAT search

Generated by `search/make_thomas_certificates.py`; do not edit by hand.

Welfare levels run from {s.Z} to {s.T}, with excellent lives from level {s.A} up. The search
domain was populations of size at most {s.max_size} over the levels {list(s.levels)}.
Each theorem is about axiologies on all populations over the welfare levels; the
search only supplies the instances used.
-/

namespace PopEthics.Arrhenius

'''
    OUT.write_text(header + "\n\n".join(blocks) + "\n\nend PopEthics.Arrhenius\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
