"""Turn each minimal conflicting set into a Lean theorem.

For every minimal conflicting set found on the default domain, extract a minimal
set of ground instances that is already contradictory, and write a Lean proof that
instantiates the general conditions at exactly those instances.

Usage: python3 search/make_certificates.py
"""

from pathlib import Path

from popsat import CONDITIONS, Domain, Encoding, Params, conflict_map, ground_core

OUT = Path(__file__).resolve().parent.parent / "PopEthics" / "Certificates.lean"

HYP = {
    "Trans": ("hT", "Trans R"),
    "MereAddition": ("hMA", "MereAddition R"),
    "NAE": ("hNAE", "NonAntiEgalitarianism R"),
    "AvoidRC": ("hRC", "AvoidsRepugnance R {rc_n} {high} {low}"),
    "Dominance": ("hD", "Dominance R"),
    "PigouDalton": ("hPD", "PigouDalton R"),
    "NonElitism": ("hNE", "NonElitism R {ne_m} 1"),
}
NAME = {
    "Trans": "trans",
    "MereAddition": "mereAddition",
    "NAE": "nonAntiEgalitarianism",
    "AvoidRC": "avoidsRepugnance",
    "Dominance": "dominance",
    "PigouDalton": "pigouDalton",
    "NonElitism": "nonElitism",
}
DEC = "(by decide)"


def lst(xs) -> str:
    return "[" + ", ".join(str(x) for x in xs) + "]"


def term(inst, p: Params) -> str:
    h = HYP[inst.cond][0]
    a = inst.args
    if inst.cond == "Trans":
        return f"{h}.inst {lst(a[0])} {lst(a[1])} {lst(a[2])}"
    if inst.cond == "MereAddition":
        return f"{h}.inst {lst(a[0])} {lst(a[1])} {lst(a[2])} {DEC} {DEC}"
    if inst.cond == "NAE":
        pop, w = a
        return f"{h}.inst {lst(pop)} {lst((w,) * len(pop))} {w} {DEC} {DEC} rfl"
    if inst.cond == "AvoidRC":
        (m,) = a
        return (
            f"{h}.inst {p.high} {p.low} {lst((p.low,) * m)} {lst((p.high,) * p.rc_n)} {m} "
            f"(by norm_num) (by norm_num) {DEC} rfl rfl"
        )
    if inst.cond == "Dominance":
        return f"{h}.inst {lst(a[0])} {lst(a[1])} {DEC} {DEC} {DEC}"
    if inst.cond == "PigouDalton":
        rest, hi, lo, d, before, after = a
        return (
            f"{h}.inst {lst(rest)} {lst(before)} {lst(after)} {hi} {lo} {d} "
            f"{DEC} {DEC} {DEC} {DEC}"
        )
    if inst.cond == "NonElitism":
        x, b, c, equal, elite = a
        return (
            f"{h}.inst 1 {lst(x)} {lst(equal)} {lst(elite)} {b} {c} "
            f"(by norm_num) {DEC} {DEC} {DEC} {DEC}"
        )
    raise ValueError(inst.cond)


def theorem(conds, core, p: Params) -> str:
    conds = [c for c in CONDITIONS if c in conds]
    fmt = dict(rc_n=p.rc_n, high=p.high, low=p.low, ne_m=p.ne_m)
    hyps = "\n    ".join(f"({HYP[c][0]} : {HYP[c][1].format(**fmt)})" for c in conds)
    name = "conflict_" + "_".join(NAME[c] for c in conds)
    counts = ", ".join(f"{sum(i.cond == c for i in core)} of {c}" for c in conds)
    lines = [
        f"/-- No axiology satisfies {', '.join(conds)}.",
        f"Certificate: {len(core)} ground instances ({counts}). -/",
        f"theorem {name} {{R : Axiology}}\n    {hyps} : False := by",
    ]
    order = {c: i for i, c in enumerate(conds)}
    for k, inst in enumerate(sorted(core, key=lambda i: (order[i.cond], i.args)), 1):
        lines.append(f"  have i{k} := {term(inst, p)}")
    # Only the instances above are used: the general hypotheses are cleared first.
    lines.append("  clear " + " ".join(HYP[c][0] for c in conds))
    lines.append("  grind")
    return "\n".join(lines)


def main():
    p = Params()
    dom = Domain(p)
    mus, _ = conflict_map(Encoding(dom))
    blocks = []
    for m in sorted(mus, key=lambda s: (len(s), sorted(s))):
        if not m <= set(HYP):
            print("skipping (no Lean template):", sorted(m))
            continue
        core = ground_core(dom, [c for c in CONDITIONS if c in m])
        print(f"{sorted(m)}: {len(core)} ground instances")
        blocks.append(theorem(m, core, p))
    header = f'''import PopEthics.Finite

/-!
# Conflicts found by SAT search

Generated by `search/make_certificates.py`; do not edit by hand.

Search domain: welfare levels {list(p.levels)}, populations of size at most {p.max_size}.
Each theorem below is about axiologies on *all* populations. The search only supplies
the finitely many instances of the conditions that the proof uses.
-/

namespace PopEthics

'''
    OUT.write_text(header + "\n\n".join(blocks) + "\n\nend PopEthics\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
